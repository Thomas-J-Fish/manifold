#!/usr/bin/env node
'use strict';
/* Generates src/core/chemistry/table.ts from a reference dataset.
 * Run once, offline; the output is committed. Not part of the build. */
const fs = require('node:fs');
const path = require('node:path');

const SRC = process.argv[2];
const data = JSON.parse(fs.readFileSync(SRC, 'utf8')).sort((a, b) => a.atomicNumber - b.atomicNumber);

const num = (v) => (v === null || v === undefined || v === '' || !Number.isFinite(Number(v)) ? 'NaN' : String(Number(v)));
const str = (v) => JSON.stringify(v === null || v === undefined ? '' : String(v));

const rows = data.map((d) => {
  return `  [${d.atomicNumber}, ${str(d.symbol)}, ${str(d.name)}, ${num(d.atomicMass)}, ${num(d.atomicRadius)}, ${num(d.electronegativity)}, ${num(d.ionizationEnergy)}, ${num(d.electronAffinity)}, ${num(d.meltingPoint)}, ${num(d.boilingPoint)}, ${num(d.density)}, ${str(d.groupBlock)}, ${str(d.oxidationStates)}, ${str(d.yearDiscovered)}],`;
});

const header = `/* The periodic table, as data.
 *
 * Fourteen numbers and strings per element, laid out one row per element so
 * that a wrong value is a one-line diff rather than a hunt through an object
 * literal. Compiled from PubChem's periodic table dataset; the values are
 * measurements, and where one has never been measured — the electronegativity
 * of neon, the boiling point of oganesson — the entry is NaN rather than a
 * zero that would plot as a real data point at the bottom of the axis.
 *
 * Generated by tools/gen/elements.js and then committed. It is data, not code,
 * and it does not change.
 *
 * Radii are van der Waals in picometres, ionisation energies and electron
 * affinities in electronvolts, temperatures in kelvin, densities in g/cm³.
 */

export type ElementRow = [
  number, // atomic number
  string, // symbol
  string, // name
  number, // relative atomic mass
  number, // van der Waals radius, pm
  number, // electronegativity, Pauling
  number, // first ionisation energy, eV
  number, // electron affinity, eV
  number, // melting point, K
  number, // boiling point, K
  number, // density, g/cm³
  string, // category
  string, // common oxidation states
  string, // year discovered
];

export const ELEMENT_ROWS: ElementRow[] = [
`;

fs.writeFileSync(
  path.join(__dirname, '..', '..', 'src', 'core', 'chemistry', 'table.ts'),
  `${header}${rows.join('\n')}\n];\n`,
);
process.stdout.write(`wrote ${rows.length} elements\n`);
